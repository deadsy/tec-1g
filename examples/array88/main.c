#include "array88.h"

//-----------------------------------------------------------------------------

int main(void) {

	array88_init();

	uint8_t c = 0;

	while (1) {
		for (int8_t i = 0; i < 4; i++) {
			array88_box(i, i, 7 - i, 7 - i, i + c);
		}
		for (int n = 0; n < 20; n++) {
			array88_scan();
		}
		c += 1;
	}
}

